  function rashiIndex(p) {
    if (p == null || p === '') return null;
    if (/^\d+$/.test(String(p))) { var n = parseInt(p, 10); return n >= 0 && n < 12 ? n : null; }
    for (var i = 0; i < 12; i++) if (RASHI[i].slug === String(p).toLowerCase() || RASHI[i].hi === p || RASHI[i].en.toLowerCase() === String(p).toLowerCase()) return i;
    return null;
  }
  function report(period, dateObj, r, opts) {
    if (period === 'day') return daily(dateObj, r, opts);
    if (period === 'week') return weekly(dateObj, r);
    if (period === 'month') return monthly(dateObj, r);
    return yearly(dateObj, r);
  }

