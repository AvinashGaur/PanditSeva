    var sections = {};
    var excl = mode === 'day' ? ['Moon'] : (mode === 'month' ? ['Moon'] : []);
    AREAS.forEach(function (a) { sections[a] = buildSection(an, a, mode, { exclude: excl, max: a === 'general' ? 3 : 2, stars: stars[a] }); });
