  /** Real sidereal positions at local time (hourLocal in zone tz) on y-m-d */
  function positions(y, m, d, hourLocal, tz) {
    if (hourLocal == null) hourLocal = 7;
    if (tz == null) tz = 5.5;
    var jd = Astro.julianDay(y, m, d, hourLocal - tz);
    var trop = Astro.tropicalLongitudes(jd), trop2 = Astro.tropicalLongitudes(jd + 1), ay = Astro.lahiriAyanamsa(jd);
    var lon = {}, sign = {}, retro = {};
    KEYS.forEach(function (k) {
      lon[k] = rev(trop[k] - ay);
      if (k === 'Rahu' || k === 'Ketu') retro[k] = true;
      else if (k === 'Sun' || k === 'Moon') retro[k] = false;
      else retro[k] = rev(trop2[k] - trop[k]) > 180;
    });
    lon.Moon = Panchang.moonSid(jd);           // Meeus-accurate Moon
    KEYS.forEach(function (k) { sign[k] = Math.floor(lon[k] / 30) % 12; });
    return { jd: jd, y: y, m: m, d: d, lon: lon, sign: sign, retro: retro };
  }

